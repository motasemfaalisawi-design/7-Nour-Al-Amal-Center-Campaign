def tag_region(item):
    """يحدد region (gaza/west_bank/unknown) وcity من الموقع الخام + النص."""
    loc = item.get("location_raw") or ""
    text = " ".join(filter(None, [loc, item.get("title"), item.get("detail_excerpt")]))
    for name, city in GAZA_CITIES.items():
        if name in loc:
            return "gaza", city
    for hint in WB_HINTS:
        if hint in loc:
            return "west_bank", loc or None
    # الموقع غير حاسم — نبحث في النص عن دلالة تنفيذ في غزة
    for name, city in GAZA_CITIES.items():
        if name in text:
            return "gaza", city
    return "unknown", loc or None


def tag_sector(item):
    """يعيد القطاع الموحد — الفئة الرسمية أولاً، ثم العنوان، ثم التفاصيل."""
    for text in (item.get("sector_raw"), item.get("title"), item.get("detail_excerpt")):
        if not text:
            continue
        for sector, keywords in SECTORS.items():
            for kw in keywords:
                if kw in text:
                    return sector
    return "أخرى"


def normalize_deadline(raw):
    """يوحّد صيغة التاريخ إلى YYYY-MM-DD إن أمكن."""
    if not raw:
        return None
    if re.match(r"^\d{4}-\d{2}-\d{2}$", raw):  # جاهز من المصدر
        return raw
    m = re.match(r"(\d{1,2})[/\-.](\d{1,2})[/\-.](\d{2,4})", raw)
    if not m:
        return None
    d, mo, y = int(m.group(1)), int(m.group(2)), int(m.group(3))
    if y < 100:
        y += 2000
    if not (1 <= mo <= 12 and 1 <= d <= 31):
        return None
    return f"{y:04d}-{mo:02d}-{d:02d}"


def normalize(items):
    out = []
    for it in items:
        region, city = tag_region(it)
        out.append({
            **it,
            "id": f'{it["source"]}:{it.get("source_id") or abs(hash(it["title"])) % 10**8}',
            "region": region,
            "city": city,
            "sector": tag_sector(it),
            "deadline": normalize_deadline(it.get("deadline_raw")),
        })
    return out
